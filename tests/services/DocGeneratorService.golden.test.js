const template = '<title>{{TITLE}}</title><h1>{{TITLE}}</h1>{{DESCRIPTION}}{{BASE_URL}}<nav>{{TOC}}</nav><main>{{CONTENT}}</main><footer>Generated on {{DATE}}</footer>';

describe('DocGeneratorService golden output', () => {
    let service;

    beforeEach(() => {
        const repository = {
            getAllPersistedEndpointData: jest.fn(async (collectionId, endpointId) => persisted[endpointId] ?? null)
        };
        service = new DocGeneratorService(repository);
        Object.keys(DocGeneratorService).forEach(key => {
            if (key.startsWith('_cached_')) {
                delete DocGeneratorService[key];
            }
        });
        global.fetch = jest.fn().mockResolvedValue({ ok: true, text: () => Promise.resolve(template) });
    });

    test('markdown without persisted data or code samples', async () => {
        const markdown = await service.generateMarkdown(collection);

        expect(withoutDate(markdown)).toBe(fixture('docgen.plain.md'));
    });

    test('markdown with persisted data and code samples', async () => {
        const markdown = await service.generateMarkdown(collection, {
            includePersistedData: true,
            languages: ['curl', 'python', 'javascript-fetch', 'not-a-language']
        });

        expect(withoutDate(markdown)).toBe(fixture('docgen.full.md'));
    });

    test('html with persisted data and code samples', async () => {
        const html = await service.generateHtml(collection, {
            includePersistedData: true,
            languages: ['curl', 'javascript-fetch', 'not-a-language']
        });

        expect(withoutDate(html)).toBe(fixture('docgen.full.html'));
    });
});
