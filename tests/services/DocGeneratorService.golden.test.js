const FIXTURES = join(process.cwd(), 'tests', 'services', '__fixtures__');

/**
 * @param {string} name
 * @returns {string}
 */
function fixture(name) {
    return readFileSync(join(FIXTURES, name), 'utf8');
}

/**
 * @param {string} text
 * @returns {string}
 */
function withoutDate(text) {
    return text.replace(/Generated by Resonance on [^*<]+/g, 'Generated by Resonance on DATE')
        .replace(/Generated on [^<]+/g, 'Generated on DATE');
}

